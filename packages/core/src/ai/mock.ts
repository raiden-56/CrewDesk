import { ExecutionError } from '@collabspace/shared';
import type { AiProvider, CompletionRequest, CompletionResult, ProviderContent, ProviderMessage } from './provider.js';
import { estimateTokens, textOf, toolUsesOf } from './provider.js';

/**
 * Deterministic mock provider used for development and automated tests.
 * It has no network access and no intelligence: it walks a scripted plan based on
 * which tools are available and the hints in the user prompt.
 *
 * Supported hints in the prompt (for tests):
 *   [mock:fail]        -> every model request fails with a transient error
 *   [mock:fail-once]   -> the first model request of each attempt fails, later ones succeed
 *   [mock:timeout]     -> the model request never returns (used to test task timeouts)
 *   [mock:publish]     -> requests content.publish (high-risk, needs approval) if available
 *   [mock:message]     -> requests message.send (high-risk, needs approval) if available
 *   [mock:delete]      -> requests resource.delete (high-risk, needs approval) if available
 *   [mock:docs-update] -> requests docs.update (write, needs approval) if available
 *   [mock:no-tools]    -> answers directly without any tool calls
 */
const failedOnce = new Set<string>();

function hasTool(req: CompletionRequest, id: string): boolean {
  return req.tools.some((t) => t.name === id);
}

function allUserText(messages: ProviderMessage[]): string {
  return messages
    .filter((m) => m.role === 'user')
    .map((m) => textOf(m.content))
    .join('\n');
}

function calledTools(messages: ProviderMessage[]): string[] {
  return messages.filter((m) => m.role === 'assistant').flatMap((m) => toolUsesOf(m.content).map((t) => t.name));
}

function lastToolResults(messages: ProviderMessage[]): Array<{ name: string; content: string; isError: boolean }> {
  const out: Array<{ name: string; content: string; isError: boolean }> = [];
  const idToName = new Map<string, string>();
  for (const m of messages) {
    if (m.role === 'assistant') for (const t of toolUsesOf(m.content)) idToName.set(t.id, t.name);
    if (m.role === 'user') {
      for (const c of m.content) {
        if (c.type === 'tool_result') out.push({ name: idToName.get(c.toolUseId) ?? 'unknown', content: c.content, isError: c.isError ?? false });
      }
    }
  }
  return out;
}

let counter = 0;
const nextId = () => `mock_tool_${Date.now().toString(36)}_${(counter++).toString(36)}`;

function firstLine(text: string): string {
  const lines = text.split('\n').filter((l) => l.trim().length > 0);
  const taskLine = lines.find((l) => /^Task:\s*/i.test(l.trim()));
  const line = (taskLine ? taskLine.trim().replace(/^Task:\s*/i, '') : lines.find((l) => !/^please complete/i.test(l.trim()))) ?? 'the request';
  return line.replace(/\[mock:[a-z-]+\]/g, '').replace(/\[file:[a-z0-9]+\]/gi, '').trim().slice(0, 120) || 'the request';
}

function buildReport(req: CompletionRequest, prompt: string): string {
  const results = lastToolResults(req.messages);
  const search = results.filter((r) => r.name === 'web.search' || r.name === 'docs.search');
  const csv = results.find((r) => r.name === 'csv.analyze');
  const sources: string[] = [];
  const findings: string[] = [];
  for (const r of search) {
    try {
      const parsed = JSON.parse(r.content) as { results?: Array<{ title: string; snippet: string; url?: string | null; sourceId: string }> };
      for (const item of parsed.results ?? []) {
        sources.push(`- ${item.title}${item.url ? ` (${item.url})` : ''} [source:${item.sourceId}]`);
        findings.push(`- ${item.snippet.slice(0, 200).replace(/\s+/g, ' ')} [source:${item.sourceId}]`);
      }
    } catch {
      /* ignore */
    }
  }
  const title = firstLine(prompt);
  const lines = [
    `# ${title}`,
    '',
    '> Generated by the **mock AI provider**. This content is deterministic placeholder output used for development and testing; it is not a real analysis.',
    '',
    '## Summary',
    sources.length
      ? `${sources.length} approved source section(s) were retrieved for "${title}". The findings below quote retrieved content only.`
      : `No approved sources matched "${title}". No factual claims are made because nothing was retrieved.`,
    '',
    '## Findings',
    ...(findings.length ? findings : ['- No findings: approved sources returned no matches. Add knowledge sources to enable research.']),
    '',
  ];
  if (csv) {
    lines.push('## Data analysis', '```json', csv.content.slice(0, 4000), '```', '');
  }
  lines.push('## Sources', ...(sources.length ? sources : ['- None retrieved']), '', '## Open questions', '- Which additional sources should be approved for this topic?', '');
  return lines.join('\n');
}

export function createMockProvider(): AiProvider {
  return {
    name: 'mock',
    isMock: true,
    supportsTemperature: () => true,
    async complete(req: CompletionRequest): Promise<CompletionResult> {
      const prompt = allUserText(req.messages);
      const key = `${req.metadata?.taskId ?? req.metadata?.conversationId ?? 'x'}:${req.metadata?.attempt ?? 0}`;
      if (prompt.includes('[mock:fail]')) throw new ExecutionError('Mock provider failure (simulated 503)', 'TRANSIENT');
      if (prompt.includes('[mock:fail-once]') && !failedOnce.has(key)) {
        failedOnce.add(key);
        throw new ExecutionError('Mock provider failure (simulated, once)', 'TRANSIENT');
      }
      if (prompt.includes('[mock:timeout]')) {
        await new Promise<void>((resolve, reject) => {
          const t = setTimeout(resolve, req.timeoutMs + 5000);
          req.signal?.addEventListener('abort', () => {
            clearTimeout(t);
            reject(new ExecutionError('Model request aborted', 'TIMEOUT'));
          });
        });
        throw new ExecutionError('Mock provider timed out', 'TIMEOUT');
      }
      // simulate latency so progress is observable
      await new Promise((r) => setTimeout(r, 150));

      const called = calledTools(req.messages);
      const content: ProviderContent[] = [];
      const inputTokens = estimateTokens(req.system + prompt);
      const respond = (blocks: ProviderContent[], stop: 'tool_use' | 'end_turn'): CompletionResult => {
        const outText = JSON.stringify(blocks);
        if (stop === 'end_turn') req.onTextDelta?.(textOf(blocks));
        return {
          content: blocks,
          stopReason: stop,
          usage: { inputTokens, outputTokens: estimateTokens(outText), available: true },
          model: req.model || 'mock-model',
          provider: 'mock',
        };
      };

      const noTools = prompt.includes('[mock:no-tools]') || req.tools.length === 0;
      const searchTool = hasTool(req, 'docs.search') ? 'docs.search' : hasTool(req, 'web.search') ? 'web.search' : null;
      const csvRequested = hasTool(req, 'csv.analyze') && /csv|dataset|analy[sz]e the data/i.test(prompt);
      const fileIdMatch = prompt.match(/\[file:([a-z0-9]+)\]/i);

      if (!noTools) {
        if (csvRequested && !called.includes('csv.analyze') && fileIdMatch) {
          content.push({ type: 'text', text: 'Analyzing the provided CSV file.' });
          content.push({ type: 'tool_use', id: nextId(), name: 'csv.analyze', input: { fileId: fileIdMatch[1] } });
          return respond(content, 'tool_use');
        }
        if (searchTool && !called.includes(searchTool)) {
          content.push({ type: 'text', text: `Searching approved sources for "${firstLine(prompt)}".` });
          content.push({ type: 'tool_use', id: nextId(), name: searchTool, input: { query: firstLine(prompt).slice(0, 200) || 'overview', limit: 5 } });
          return respond(content, 'tool_use');
        }
        if (hasTool(req, 'report.generate') && !called.includes('report.generate')) {
          content.push({ type: 'text', text: 'Compiling the findings into a report artifact.' });
          content.push({ type: 'tool_use', id: nextId(), name: 'report.generate', input: { title: firstLine(prompt) || 'Report', format: 'MARKDOWN', content: buildReport(req, prompt) } });
          return respond(content, 'tool_use');
        }
        if (!hasTool(req, 'report.generate') && hasTool(req, 'document.create_draft') && !called.includes('document.create_draft')) {
          content.push({ type: 'tool_use', id: nextId(), name: 'document.create_draft', input: { title: firstLine(prompt) || 'Draft', content: buildReport(req, prompt) } });
          return respond(content, 'tool_use');
        }
        if (hasTool(req, 'task.create_draft') && /plan|breakdown|milestone/i.test(prompt) && !called.includes('task.create_draft')) {
          content.push({ type: 'tool_use', id: nextId(), name: 'task.create_draft', input: { title: `Draft task: ${firstLine(prompt).slice(0, 80)}`, description: 'Generated by the mock planner.', priority: 'NORMAL' } });
          return respond(content, 'tool_use');
        }
        const artifactResult = lastToolResults(req.messages).find((r) => r.name === 'report.generate' || r.name === 'document.create_draft');
        let artifactId: string | null = null;
        try {
          artifactId = artifactResult ? ((JSON.parse(artifactResult.content) as { artifactId?: string }).artifactId ?? null) : null;
        } catch {
          artifactId = null;
        }
        if (prompt.includes('[mock:publish]') && hasTool(req, 'content.publish') && !called.includes('content.publish') && artifactId) {
          content.push({ type: 'text', text: 'Requesting permission to publish the report externally.' });
          content.push({ type: 'tool_use', id: nextId(), name: 'content.publish', input: { artifactId, destination: 'company-blog' } });
          return respond(content, 'tool_use');
        }
        if (prompt.includes('[mock:message]') && hasTool(req, 'message.send') && !called.includes('message.send')) {
          content.push({ type: 'tool_use', id: nextId(), name: 'message.send', input: { channel: 'general', text: `Report ready: ${firstLine(prompt)}` } });
          return respond(content, 'tool_use');
        }
        if (prompt.includes('[mock:delete]') && hasTool(req, 'resource.delete') && !called.includes('resource.delete') && artifactId) {
          content.push({ type: 'tool_use', id: nextId(), name: 'resource.delete', input: { resourceType: 'artifact', resourceId: artifactId, reason: 'Mock cleanup' } });
          return respond(content, 'tool_use');
        }
        if (prompt.includes('[mock:docs-update]') && hasTool(req, 'docs.update') && !called.includes('docs.update') && artifactId) {
          content.push({ type: 'tool_use', id: nextId(), name: 'docs.update', input: { artifactId, newContent: `# Updated\n\nUpdated by mock provider.\n`, summary: 'Mock update of the generated document' } });
          return respond(content, 'tool_use');
        }
      }

      const results = lastToolResults(req.messages);
      const denied = results.filter((r) => r.isError);
      const summaryLines = [
        `**Mock provider response** for: ${firstLine(prompt)}`,
        '',
        results.length ? `Executed ${results.length} tool call(s): ${[...new Set(results.map((r) => r.name))].join(', ')}.` : 'No tools were used.',
        denied.length ? `${denied.length} tool call(s) were denied or failed: ${denied.map((d) => d.name).join(', ')}.` : '',
        '',
        'This text was produced by the deterministic mock provider. Configure a real AI provider (AI_PROVIDER=anthropic or openai) for genuine results.',
      ].filter((l) => l !== undefined);
      content.push({ type: 'text', text: summaryLines.join('\n') });
      return respond(content, 'end_turn');
    },
    async embed(texts: string[]): Promise<number[][]> {
      // cheap deterministic hashing embedding (64 dims) for tests
      return texts.map((t) => {
        const v = new Array<number>(64).fill(0);
        for (let i = 0; i < t.length; i++) v[i % 64] = (v[i % 64] ?? 0) + t.charCodeAt(i) / 255;
        const norm = Math.sqrt(v.reduce((a, b) => a + b * b, 0)) || 1;
        return v.map((x) => x / norm);
      });
    },
  };
}
